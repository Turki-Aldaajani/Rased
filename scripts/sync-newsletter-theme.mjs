// Extracts the design system of Issue #1 into a TypeScript module, so every
// generated issue is rendered with exactly the same stylesheet, icons and
// behaviour — and Issue #1 itself is never touched.
//
//   npm run newsletter:theme
//
// Re-run it whenever docs/newsletter/01/index.html changes on purpose.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "docs/newsletter/01/index.html");
const target = join(root, "src/lib/newsletter/theme.generated.ts");

const html = readFileSync(source, "utf8").replace(/\r\n/g, "\n");

function between(open, close, from = 0) {
  const start = html.indexOf(open, from);
  if (start === -1) throw new Error(`Not found: ${open}`);
  const end = html.indexOf(close, start + open.length);
  if (end === -1) throw new Error(`Not closed: ${open}`);
  return { inner: html.slice(start + open.length, end), outer: html.slice(start, end + close.length), end };
}

const headScript = between("<script>", "</script>");
const style = between("<style>", "</style>");
const sprite = between('<svg class="sprite"', "</svg>");
const arch = between('<svg class="arch"', "</svg>");
const diamonds = between('<svg class="diamond-row"', "</svg>");
const bodyScriptStart = html.lastIndexOf("<script>");
const bodyScript = between("<script>", "</script>", bodyScriptStart);

const entries = {
  NEWSLETTER_HEAD_SCRIPT: headScript.inner,
  NEWSLETTER_CSS: style.inner,
  NEWSLETTER_SPRITE: sprite.outer,
  NEWSLETTER_ARCH: arch.outer,
  NEWSLETTER_DIAMONDS: diamonds.outer,
  NEWSLETTER_BODY_SCRIPT: bodyScript.inner,
};

const body = Object.entries(entries)
  .map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};`)
  .join("\n\n");

writeFileSync(
  target,
  `// GENERATED by scripts/sync-newsletter-theme.mjs from docs/newsletter/01/index.html.\n` +
    `// Do not edit by hand — change Issue #1's design, then run \`npm run newsletter:theme\`.\n\n` +
    body +
    "\n",
);

console.log(`Wrote ${target}`);
for (const [name, value] of Object.entries(entries)) {
  console.log(`  ${name.padEnd(24)} ${value.length} chars`);
}
